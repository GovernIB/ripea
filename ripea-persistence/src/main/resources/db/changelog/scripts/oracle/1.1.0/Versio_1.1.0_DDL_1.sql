-- Monitor d'excepcions: no es desa una fila nova per cada repeticio d'una mateixa excepcio en un curt
-- espai de temps (evita saturar el tablespace RIPEA_LOB). En lloc d'aixo s'incrementa un comptador.
ALTER TABLE IPA_EXCEPCIO_LOG ADD SIGNATURA VARCHAR2(64 CHAR);
ALTER TABLE IPA_EXCEPCIO_LOG ADD NUM_OCURRENCIES NUMBER(10,0) DEFAULT 1 NOT NULL;
ALTER TABLE IPA_EXCEPCIO_LOG ADD DATA_DARRERA TIMESTAMP(6);
UPDATE IPA_EXCEPCIO_LOG SET DATA_DARRERA = DATA WHERE DATA_DARRERA IS NULL;
CREATE INDEX IPA_EXCEPCIO_LOG_SIGN_IDX ON IPA_EXCEPCIO_LOG (SIGNATURA, DATA_DARRERA);
