    CREATEDDATE TIMESTAMP,
    LASTMODIFIEDBY_CODI VARCHAR(64),
    LASTMODIFIEDDATE TIMESTAMP,
    CONSTRAINT IPA_INTEGRACIO_ACCIO_PK PRIMARY KEY (ID)
