CREATE TABLE IPA_INTEGRACIO_ACCIO (
    ID BIGINT NOT NULL,
    DATA TIMESTAMP NOT NULL,
    INTEGRACIO_CODI VARCHAR(64) NOT NULL,
    DESCRIPCIO VARCHAR(1024),
    ENDPOINT VARCHAR(1024),
    PARAMETRES TEXT,
    TIPUS VARCHAR(32),
    TEMPS_RESPOSTA BIGINT,
