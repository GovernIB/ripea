SELECT EXP.ID, EXP.CODI, EXP.ORGAN_GESTOR_ID as OG_EXP, MN.ID, MN.CODI, MN.ACTIU, ME.GESTIO_AMB_GRUPS_ACTIVA, ME.PERMIS_DIRECTE, OG2.ID as OG_PROC, OG2.CODI, OG2.NOM
FROM IPA_EXPEDIENT EXP
, IPA_ORGAN_GESTOR OG
, IPA_NODE NOD
, IPA_CONTINGUT CON
, IPA_METANODE MN
, IPA_METAEXPEDIENT ME
, IPA_ORGAN_GESTOR OG2
WHERE EXP.ORGAN_GESTOR_ID=OG.ID(+)
AND EXP.ID=NOD.ID AND NOD.ID=CON.ID AND NOD.METANODE_ID=MN.ID AND MN.ID=ME.ID AND ME.ORGAN_GESTOR_ID=OG2.ID(+)
AND CON.ENTITAT_ID=1 AND CON.ESBORRAT = 0;-- AND EXP.ORGAN_GESTOR_ID<>OG2.ID;