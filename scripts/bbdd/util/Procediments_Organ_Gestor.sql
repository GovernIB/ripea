SELECT MN.ID, MN.CODI, MN.ACTIU, ME.GESTIO_AMB_GRUPS_ACTIVA, ME.PERMIS_DIRECTE, OG.ID, OG.CODI, OG.NOM
FROM IPA_METAEXPEDIENT ME
, IPA_ORGAN_GESTOR OG
, IPA_METANODE MN
WHERE MN.ID=ME.ID
AND ME.ORGAN_GESTOR_ID=OG.ID(+)
AND MN.ENTITAT_ID=1;

